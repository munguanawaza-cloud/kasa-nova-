                        icon = Icons.Default.AutoAwesome,
                        tint = CopperGold,
                        title = "KASA AI Bilingual Advisor (FR / AR)",
                        detail = "Read-only Gemini 3.8 Flash analysis for stock, collections & FR/AR sales offers."
